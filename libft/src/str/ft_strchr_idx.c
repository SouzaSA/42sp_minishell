#include "libft.h"

int	ft_strchr_idx(const char *s, int c)
{
	int		i;

	i = 0;
	if (s)
	{
		while (s[i] != '\0')
		{
			if (s[i] == (char) c)
				break ;
			i++;
		}
		if (c == '\0')
			i++;
	}
	return (i);
}
